"""Apply an approved setup.yml: bootstrap, generate files, grant access, wire Azure DevOps.

Each step checks current state and does only what is missing, so re-running after a
fix repeats finished steps as no-ops. The first failure stops with one message.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from urllib.parse import quote

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from approve import digest  # noqa: E402
from ops import Ops, StepError  # noqa: E402
from render_pipelines import render_all  # noqa: E402
from profiles import ProfileError, legacy_environments, normalize_setup  # noqa: E402

ASSETS = Path(__file__).resolve().parents[1] / "assets"
RANK = {"Viewer": 0, "Contributor": 1, "Member": 2, "Admin": 3}
REQUIRED_VARIABLES = ("FABRIC_TENANT_ID", "FABRIC_APP_ID")


def load_setup(path: Path) -> dict:
    approved = path.with_name("setup.approved")
    if not approved.exists():
        raise StepError("setup.yml is not approved; review SETUP.md and run approve.py")
    if approved.read_text(encoding="utf-8").strip() != digest(path):
        raise StepError("setup.yml changed after approval; review it and run approve.py again")
    try:
        return normalize_setup(yaml.safe_load(path.read_text(encoding="utf-8")))
    except ProfileError as exc:
        raise StepError(str(exc)) from exc


def dump(value) -> str:
    return yaml.safe_dump(value, sort_keys=False, default_flow_style=False)


def slug(text: str, fallback: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", (text or "").lower()).strip("_") or fallback


# ---- generate (pure) ----------------------------------------------------------------------------

def generate(setup: dict, ids: dict[str, str]) -> dict[str, str]:
    """Return every generated file as {repo-relative path: text}; identical input gives identical output."""
    setup = normalize_setup(setup)
    envs = legacy_environments(setup)
    keys = tuple(envs)
    sp = setup["service_principal"]
    config = {
        "core": {
            "workspace_id": {env: ids[env] for env in keys},
            "repository_directory": "../../" + setup["repository"]["source_root"],
            "parameter": "parameter.yml",
            "item_types_in_scope": sorted({m["type"] for m in setup["managed_items"]}),
        },
        "constants": {"DEFAULT_API_ROOT_URL": "https://api.fabric.microsoft.com"},
        "publish": {"skip": False},
        "unpublish": {"skip": True},
    }
    manifest = {"version": 2, "source_root": setup["repository"]["source_root"], "profiles": setup["profiles"]}
    for env in keys:
        workspace = envs[env]["workspace"]
        manifest[f"{env.lower()}_workspace"] = {"id": ids[env], "name": workspace["name"], "capacity": workspace["capacity"]}
    manifest["deployment_identity"] = {"app_id": sp["app_id"], "object_id": sp["object_id"]}
    manifest["managed_items"] = [
        {"folder": m["folder"], "type": m["type"], "logical_id": m.get("logical_id"), "dependencies": m["dependencies"]} for m in setup["managed_items"]
    ]
    manifest["excluded"] = setup["excluded"]
    bindings = {
        "version": 1,
        "connections": [
            {"key": slug(c["display_name"], c["id"][:8]), "connection_id": c["id"], "display_name": c["display_name"], "required_permission": c["required_permission"]}
            for c in setup["connections"]
        ],
    }
    rules = []
    for rule in setup["bindings"]["rules"]:
        rule = dict(rule)
        replacement = dict(rule.get("replace_value", {}))
        fallback = next(iter(replacement.values()), None)
        if fallback is not None:
            for key in keys:
                replacement.setdefault(key, fallback)
        rule["replace_value"] = replacement
        rules.append(rule)
    parameter = "# Generated by fabric-cicd plan/apply from setup.yml; do not edit by hand.\n" + dump({"find_replace": rules})
    files = {
        "cicd/fabric/config.yml": "# fabric-cicd configuration. Paths are resolved from this file's directory.\n" + dump(config),
        "cicd/fabric/managed-items.yml": dump(manifest),
        "cicd/fabric/connection-bindings.yml": dump(bindings),
        "cicd/fabric/parameter.yml": parameter,
    }
    render_input = {
        "profiles": setup["profiles"],
        "branches": {env: envs[env]["branch"] for env in keys},
        "environments": {
            env: {
                "workspace_id": ids[env],
                "variable_group": envs[env]["variable_group"]["name"],
                "ado_environment": envs[env]["ado_environment"],
                "pipeline_name": envs[env]["pipeline_name"],
                "private_pool": envs[env]["private_pool"]["name"],
                "key_vault_service_connection": envs[env]["key_vault"]["service_connection"],
                "key_vault_name": envs[env]["key_vault"]["name"],
                "key_vault_secret": envs[env]["key_vault"]["secret"],
            }
            for env in keys
        },
    }
    for name, text in render_all(render_input).items():
        files[f"cicd/fabric/{name}"] = text
    for source in sorted((ASSETS / "cicd" / "fabric").iterdir()):
        if source.is_file() and source.suffix in (".py", ".lock", ".txt"):
            files[f"cicd/fabric/{source.name}"] = source.read_text(encoding="utf-8")
    files["cicd/shared/secret_scan.py"] = (ASSETS / "cicd" / "shared" / "secret_scan.py").read_text(encoding="utf-8")
    return dict(sorted(files.items()))


def write_files(repo: Path, files: dict[str, str]) -> list[str]:
    changed = []
    for relative, text in files.items():
        path = repo / relative
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        changed.append(relative)
    return changed


def preflight_overwrites(repo: Path, setup: dict) -> list[str]:
    """Fail closed on hand-authored files before workspace or DevOps writes."""
    ids = {key: str((profile["workspace"].get("id") or "")) for key, profile in setup["profiles"].items()}
    generated = set(generate(setup, ids))
    root = repo / "cicd" / "fabric"
    existing = {str(path.relative_to(repo)).replace("\\", "/") for path in root.rglob("*") if path.is_file()} if root.exists() else set()
    planning = {"cicd/fabric/setup.yml", "cicd/fabric/setup.approved", "cicd/fabric/SETUP.md"}
    unmanaged = sorted(existing - generated - planning)
    accepted = set(setup.get("overwrite_acknowledged", []))
    unacknowledged = [path for path in unmanaged if path not in accepted]
    if unacknowledged:
        raise StepError("regeneration would overwrite files not generated by fabric-cicd; acknowledge them in setup.yml: " + ", ".join(unacknowledged))
    return sorted(existing & generated)


# ---- steps --------------------------------------------------------------------------------------

def bootstrap(setup: dict, ops: Ops) -> dict[str, str]:
    """Create or reuse each workspace and its schema-enabled Lakehouses; never runs a workload."""
    ids = {}
    lakehouses = [m["name"] for m in setup["managed_items"] if m["type"] == "Lakehouse"]
    envs = legacy_environments(setup)
    for env, config in envs.items():
        workspace = config["workspace"]
        current = ops.fab_get(f"workspaces/{workspace['id']}") if workspace.get("id") else None
        if current is None:
            match = next((w for w in (ops.fab_get("workspaces") or {}).get("value", []) if w["displayName"] == workspace["name"]), None)
            current = match
        if current is None:
            capacity = (workspace.get("capacity") or {}).get("id")
            if not capacity:
                raise StepError(f"{env}: workspace '{workspace['name']}' does not exist and no capacity is approved; set one in setup.yml and re-run plan")
            current = ops.fab_post("workspaces", {"displayName": workspace["name"], "capacityId": capacity})
            print(f"{env}: created workspace '{workspace['name']}'")
        else:
            print(f"{env}: workspace '{workspace['name']}' exists")
        ids[env] = current["id"]
        existing = {i["displayName"] for i in (ops.fab_get(f"workspaces/{ids[env]}/items") or {}).get("value", []) if i["type"] == "Lakehouse"}
        for name in lakehouses:
            if name in existing:
                continue
            ops.fab_post(f"workspaces/{ids[env]}/lakehouses", {"displayName": name, "creationPayload": {"enableSchemas": True}})
            print(f"{env}: created schema-enabled Lakehouse '{name}'")
    return ids


def role_at_least(assignments: list[dict], principal: str, minimum: str) -> bool:
    return any(a["principal"]["id"].lower() == principal.lower() and RANK.get(a["role"], -1) >= RANK[minimum] for a in assignments)


def grants(setup: dict, ops: Ops, ids: dict[str, str]) -> None:
    envs = legacy_environments(setup)
    sp_id = setup["service_principal"]["object_id"]
    for env in envs:
        roles = (ops.fab_get(f"workspaces/{ids[env]}/roleAssignments") or {}).get("value")
        if roles is None:
            raise StepError(f"{env}: cannot read workspace roles; the developer needs Admin on '{envs[env]['workspace']['name']}'")
        if not role_at_least(roles, sp_id, "Contributor"):
            ops.fab_post(f"workspaces/{ids[env]}/roleAssignments", {"principal": {"id": sp_id, "type": "ServicePrincipal"}, "role": "Contributor"})
            print(f"{env}: granted the service principal Contributor")
    developer = ops.developer_object_id()
    owners: dict[str, dict] = {}
    for connection in setup["connections"]:
        label = f"connection '{connection['display_name']}' ({connection['id']})"
        roles = (ops.fab_get(f"connections/{connection['id']}/roleAssignments") or {}).get("value")
        if roles is None:
            raise StepError(f"cannot read roles of {label}; ask its owner to grant the developer Owner or User")
        users = [r for r in roles if r["role"] in ("User", "Owner", "UserWithReshare")]
        for who, principal, kind in (("service principal", sp_id, "ServicePrincipal"), ("developer", developer, "User")):
            if principal and any(r["principal"]["id"].lower() == principal.lower() for r in users):
                continue
            if not principal:
                raise StepError("cannot resolve the signed-in developer; run 'az login'")
            try:
                ops.fab_post(f"connections/{connection['id']}/roleAssignments", {"principal": {"id": principal, "type": kind}, "role": "User"})
            except StepError as exc:
                raise StepError(f"the {who} lacks the User role on {label} and it could not be granted ({exc}); ask the connection owner to add it") from exc
            print(f"granted the {who} User on {label}")
        if connection["id"] in setup.get("pipeline_invocation_connections", []):
            for role in roles:
                if role["role"] == "Owner":
                    owners[role["principal"]["id"]] = role["principal"]
    for env in envs:
        roles = (ops.fab_get(f"workspaces/{ids[env]}/roleAssignments") or {}).get("value", [])
        for owner_id, principal in sorted(owners.items()):
            if not role_at_least(roles, owner_id, "Contributor"):
                ops.fab_post(f"workspaces/{ids[env]}/roleAssignments", {"principal": {"id": owner_id, "type": principal["type"]}, "role": "Contributor"})
                print(f"{env}: granted the pipeline-invocation connection owner Contributor")


def azure_devops(setup: dict, ops: Ops, repo: Path) -> None:
    envs = legacy_environments(setup)
    ado = setup["repository"]["azure_devops"]
    org, project = ado["organization"].rstrip("/"), ado["project"]
    base = f"{org}/{project.replace(' ', '%20')}/_apis"
    groups, group_ids = {}, {}
    for env in envs:
        name = envs[env]["variable_group"]["name"]
        if name in groups:
            continue
        found = ops.az_json("pipelines", "variable-group", "list", "--group-name", name, "--org", org, "--project", project)
        if not found:
            raise StepError(f"variable group '{name}' does not exist; create it in Library with {', '.join(REQUIRED_VARIABLES)}")
        variables = found[0].get("variables", {})
        missing = [v for v in REQUIRED_VARIABLES if v not in variables]
        if missing:
            raise StepError(f"variable group '{name}' is missing {', '.join(missing)}; add them in Library")
        if str(variables["FABRIC_APP_ID"].get("value", "")).lower() != setup["service_principal"]["app_id"]:
            raise StepError(f"variable group '{name}': FABRIC_APP_ID does not match service principal {setup['service_principal']['app_id']}")
        groups[name], group_ids[name] = found[0], found[0]["id"]
    pools = ops.az_json("pipelines", "pool", "list", "--org", org) or []
    service_connections = ops.az_json("devops", "service-endpoint", "list", "--org", org, "--project", project) or []
    pool_names = {pool.get("name") for pool in pools}
    endpoint_by_name = {endpoint.get("name"): endpoint for endpoint in service_connections}
    queues = {}
    endpoints = {}
    for env in envs:
        config = envs[env]
        pool_name = config["private_pool"]["name"]
        if pool_name not in pool_names:
            raise StepError(f"{env}: private pool '{pool_name}' does not exist or is not visible; ask the Azure DevOps administrator to authorize it")
        queue = (ops.ado_rest("get", f"{base}/distributedtask/queues?queueName={quote(pool_name)}&api-version=7.1") or {}).get("value", [])
        if not queue:
            raise StepError(f"{env}: private pool '{pool_name}' has no authorized Azure DevOps queue; ask the project administrator to enable it")
        queues[env] = queue[0]["id"]
        key_vault = config["key_vault"]
        if not key_vault.get("name") or not key_vault.get("secret"):
            raise StepError(f"{env}: Key Vault name and secret reference are required in setup.yml")
        endpoint = endpoint_by_name.get(key_vault["service_connection"])
        if not endpoint:
            raise StepError(f"{env}: Key Vault service connection '{key_vault['service_connection']}' does not exist; create or authorize the WIF connection")
        if key_vault.get("service_connection_id") not in (None, endpoint["id"]):
            raise StepError(f"{env}: Key Vault service connection ID changed; re-run plan")
        endpoints[env] = endpoint["id"]
    environments = {e["name"]: e["id"] for e in (ops.ado_rest("get", f"{base}/distributedtask/environments?api-version=7.1") or {}).get("value", [])}
    for env in envs:
        config = envs[env]
        if config["ado_environment"] not in environments:
            created = ops.ado_rest("post", f"{base}/distributedtask/environments?api-version=7.1", {"name": config["ado_environment"]})
            if not created or not created.get("id"):
                raise StepError(f"could not create deployment environment '{config['ado_environment']}'; ask the Azure DevOps project administrator to create or authorize it")
            environments[config["ado_environment"]] = created["id"]
            print(f"created deployment environment '{config['ado_environment']}'")
    for env in envs:
        config = envs[env]
        if not (repo / config["pipeline_yaml"]).exists():
            raise StepError(f"{config['pipeline_yaml']} is not generated; re-run apply")
        found = ops.az_json("pipelines", "list", "--name", config["pipeline_name"], "--org", org, "--project", project)
        if not found:
            raise StepError(f"pipeline '{config['pipeline_name']}' is not registered; commit the generated files, then run: az pipelines create --name \"{config['pipeline_name']}\" --yml-path {config['pipeline_yaml']} --branch {config['branch'] if '*' not in config['branch'] else 'main'} --skip-first-run")
        detail = ops.az_json("pipelines", "show", "--id", str(found[0]["id"]), "--org", org, "--project", project) or {}
        if detail.get("process", {}).get("yamlFilename") != config["pipeline_yaml"]:
            raise StepError(f"pipeline '{config['pipeline_name']}' points at {detail.get('process', {}).get('yamlFilename')}, expected {config['pipeline_yaml']}")
        pipeline_id = found[0]["id"]
        for kind, resource in (
            ("variablegroup", group_ids[config["variable_group"]["name"]]),
            ("environment", environments[config["ado_environment"]]),
            ("endpoint", endpoints[env]),
            ("queue", queues[env]),
        ):
            url = f"{base}/pipelines/pipelinePermissions/{kind}/{resource}?api-version=7.1-preview.1"
            current = ops.ado_rest("get", url) or {}
            if current.get("allPipelines", {}).get("authorized") or any(p.get("id") == pipeline_id and p.get("authorized") for p in current.get("pipelines", [])):
                continue
            ops.ado_rest("patch", url, {"pipelines": [{"id": pipeline_id, "authorized": True}]})
            print(f"authorized pipeline '{config['pipeline_name']}' for {kind} {resource}")


def main(argv=None, ops: Ops | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default=".")
    parser.add_argument("--setup", default="cicd/fabric/setup.yml")
    args = parser.parse_args(argv)
    repo = Path(args.repo).resolve()
    setup = load_setup(repo / args.setup)
    ops = ops or Ops()
    overwritten = preflight_overwrites(repo, setup)
    if overwritten:
        print("regeneration may overwrite: " + ", ".join(overwritten))
    ids = bootstrap(setup, ops)
    changed = write_files(repo, generate(setup, ids))
    print(f"generated files: {len(changed)} written, rest unchanged")
    grants(setup, ops, ids)
    azure_devops(setup, ops, repo)
    print("apply finished")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
